#!/usr/bin/env python3
"""Generate THIRD_PARTY_NOTICES.md: the licences of everything ARGUS's
binaries and web UI are built from, which the release redistributes.

    scripts/third-party-notices.py           # rewrite THIRD_PARTY_NOTICES.md
    scripts/third-party-notices.py --check   # fail if it is out of date

Run it whenever go.mod or web/package-lock.json changes. It needs
`go-licenses` (go install github.com/google/go-licenses/v2@v2.0.1) and the
web dependencies installed (cd web && npm ci).

Go modules come from go-licenses, for the four binaries. npm packages are the
web UI's production dependencies, the ones bundled into the hub. Each entry
carries the licence text found in the package, and Apache NOTICE files where
a package has one, as those licences require.
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'THIRD_PARTY_NOTICES.md'
BINARIES = ['./cmd/hub', './cmd/agent', './cmd/cli-runner', './cmd/argusctl']
LICENSE_NAMES = ('LICENSE', 'LICENCE', 'COPYING', 'LICENSE.md', 'LICENSE.txt', 'LICENCE.md',
                 'COPYING.md', 'LICENSE-MIT', 'LICENSE.MIT', 'license', 'license.md')


def go_licenses_bin():
    found = shutil.which('go-licenses') or str(Path.home() / 'go' / 'bin' / 'go-licenses')
    if not Path(found).exists():
        sys.exit('go-licenses not found: go install github.com/google/go-licenses/v2@v2.0.1')
    return found


def go_modules():
    with tempfile.NamedTemporaryFile('w', suffix='.tpl', delete=False) as tpl:
        tpl.write('{{range .}}{{.Name}}|{{.Version}}|{{.LicenseName}}|{{.LicensePath}}\n{{end}}')
    try:
        out = subprocess.run([go_licenses_bin(), 'report', *BINARIES, '--template', tpl.name],
                             cwd=ROOT, capture_output=True, text=True, check=True).stdout
    finally:
        os.unlink(tpl.name)
    mods = []
    for line in out.splitlines():
        name, version, lic, path = line.split('|', 3)
        if name == 'argus':
            continue
        path = Path(path)
        notice = None
        for n in ('NOTICE', 'NOTICE.txt', 'NOTICE.md'):
            if (path.parent / n).is_file():
                notice = (path.parent / n).read_text(errors='replace')
        mods.append((name, version, lic, path.read_text(errors='replace'), notice))
    return sorted(mods)


def npm_packages():
    web = ROOT / 'web'
    out = subprocess.run(['npm', 'ls', '--omit=dev', '--all', '--parseable'], cwd=web,
                         capture_output=True, text=True).stdout
    pkgs = {}
    for line in out.splitlines():
        d = Path(line)
        if d == web or not (d / 'package.json').is_file():
            continue
        meta = json.loads((d / 'package.json').read_text())
        text = None
        for n in LICENSE_NAMES:
            if (d / n).is_file():
                text = (d / n).read_text(errors='replace')
                break
        if text is None:
            for f in sorted(d.iterdir()):
                if f.is_file() and f.name.upper().startswith(('LICENSE', 'LICENCE', 'COPYING')):
                    text = f.read_text(errors='replace')
                    break
        lic = meta.get('license') or (meta.get('licenses') or [{}])[0].get('type', 'UNKNOWN')
        pkgs[(meta['name'], meta['version'])] = (lic, text)
    return sorted((n, v, l, t) for (n, v), (l, t) in pkgs.items())


def fence(text):
    return '```text\n' + text.strip('\n') + '\n```\n'


def render():
    go = go_modules()
    npm = npm_packages()
    out = ['# Third-party notices\n',
           'ARGUS is licensed under the GNU Affero General Public License v3.0 (`LICENSE`). Its binaries\n'
           'and container images also contain the open-source software listed here, each under its own\n'
           'licence, reproduced in full below. Every licence listed is compatible with AGPL-3.0.\n',
           'Generated by `scripts/third-party-notices.py`; do not edit by hand.\n',
           '## Summary\n',
           '| Component | Version | Licence |', '|---|---|---|']
    out += [f'| {n} (Go) | {v} | {l} |' for n, v, l, _, _ in go]
    out += [f'| {n} (npm, web UI) | {v} | {l} |' for n, v, l, _ in npm]
    out.append('')
    out.append('## Also in the container images\n')
    out.append(
        '- **Base images.** The hub and agent images are built on `gcr.io/distroless/base-debian12`, and\n'
        '  the CLI runner on `node:22-trixie-slim`. Their Debian packages and Node.js carry their own\n'
        '  licences, which the images keep under `/usr/share/doc` and in the Node.js installation.\n'
        '- **Claude Code and Codex.** The CLI runner image includes `@anthropic-ai/claude-code`, subject\n'
        '  to Anthropic\'s terms (see its `README.md` and <https://www.anthropic.com/legal>), and\n'
        '  `@openai/codex`, under Apache-2.0. Their licence files are in the image with each package.\n'
        '- **MPL-2.0.** `github.com/cyphar/filepath-securejoin` is used unmodified; its source is\n'
        '  available from its module path at the version listed.\n')
    out.append('## Go modules\n')
    for n, v, l, text, notice in go:
        out.append(f'### {n} {v} ({l})\n')
        out.append(fence(text))
        if notice:
            out.append(f'NOTICE for {n}:\n')
            out.append(fence(notice))
    out.append('## npm packages (web UI)\n')
    for n, v, l, text in npm:
        out.append(f'### {n} {v} ({l})\n')
        out.append(fence(text) if text else f'Licence: {l} (the package ships no licence file).\n')
    return '\n'.join(out).rstrip('\n') + '\n'


if __name__ == '__main__':
    text = render()
    if '--check' in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit('THIRD_PARTY_NOTICES.md is out of date: run scripts/third-party-notices.py')
        print('THIRD_PARTY_NOTICES.md is up to date')
    else:
        OUT.write_text(text)
        print(f'wrote {OUT.relative_to(ROOT)}')
