// Package gitops implements the hub side of REMEDIATION_ROADMAP.md Phase 2:
// finding, in a Git repository, the file that is the actual source of truth for
// a live Kubernetes object — so a fix can be proposed where it will survive the
// next reconcile, rather than in-place where the controller reverts it.
//
// # Why this is hub-side, not agent-side
//
// lld/09-repo-gitops-design.md puts the repository work on the hub, and the
// reasons hold: repository credentials live hub-side (repository_bindings),
// and having every cluster agent clone customer repositories would multiply
// both the credential surface and the egress requirement by the size of the
// fleet. The agent's job stays what it was — read the cluster, report what it
// sees (get_gitops_ownership now reports the repo URL and pinned revision,
// WORKLOG §121). The hub does the rest.
//
// # What is deliberately NOT here yet
//
// **No rendering.** Nothing in this package executes Helm templates, Kustomize
// builds, or any repo-provided script, and that is what makes it safe to run
// in-process today. lld/09 §2 requires a gVisor-sandboxed, network-disabled
// pod for rendering precisely because rendering evaluates attacker-supplied
// code (LLD-01 T7). Cloning a repository and parsing YAML out of it evaluates
// nothing, so it needs no sandbox — a distinction worth keeping sharp, because
// conflating them would mean either blocking this work behind a large
// infrastructure lift it does not need, or later rendering untrusted charts
// in-process because "the gitops package already reads repos."
//
// Consequence: this package reads repository files and writes proposed content
// back through the provider API. It does not evaluate a chart or an overlay,
// and it does not need to: a repository change is a set of whole-file edits
// whose diff a human reviews and merges, so the connection between an edited
// values key and the field it produces is established by the reviewer reading
// the diff, not by ARGUS claiming a render it did not perform. What that does
// and does not promise is stated in every pull-request body — see propose.go.
//
// Rendering, when it exists, adds a stronger claim (§11.4's
// `argus/verified-against-argo`). It is not a prerequisite for proposing a
// change, and treating it as one is what previously confined ARGUS to plain
// YAML manifests — see files.go's header.
package gitops

import (
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"
)

const (
	// maxManifestBytes bounds one file read. Kubernetes itself refuses
	// objects over ~1.5MB (etcd's practical limit), so a manifest larger than
	// this is not a manifest — it is a data file, a vendored blob, or an
	// attempt to make the hub allocate. Skipped rather than truncated:
	// half a YAML document parses into something that is not what the file
	// says, which is worse than not reading it.
	maxManifestBytes = 2 << 20 // 2 MiB

	// maxScannedFiles bounds a whole walk. A real GitOps repo holds hundreds
	// of manifests; a monorepo can hold hundreds of thousands of files. This
	// is a cost bound, not a security boundary — hitting it is reported, never
	// silently treated as "searched everything and found nothing", because
	// "not found" and "gave up looking" must not be indistinguishable.
	maxScannedFiles = 20000
)

// ObjectRef identifies the live object whose source file is being looked for.
// Namespace may be empty for a cluster-scoped object, and is also matched
// leniently — see documentMatches.
type ObjectRef struct {
	APIVersion string
	Kind       string
	Namespace  string
	Name       string
}

// SourceLocation is where an object is defined in a repository.
type SourceLocation struct {
	// Path is relative to the repository root, always with forward slashes.
	Path string
	// DocIndex is which YAML document within that file, 0-based. Multi-document
	// files are the norm in GitOps repos, so the file alone is not a precise
	// enough answer to edit from.
	DocIndex int
	// Line is the 1-based line where the matched document begins, for a
	// human-readable citation. Best-effort: 0 when it could not be determined.
	Line int
}

// LocateResult is the outcome of a search. Locations is empty when nothing
// matched — which is a normal answer, not an error: the object may be
// generated by a chart, live in a repo this search was not pointed at, or have
// been created outside GitOps entirely.
type LocateResult struct {
	Locations []SourceLocation
	// FilesScanned is how many YAML files were actually parsed, and Truncated
	// reports that maxScannedFiles was hit — so a caller can tell "searched
	// the repo, found nothing" from "stopped searching early".
	FilesScanned int
	Truncated    bool
}

// Locate walks root looking for YAML documents defining ref, and returns every
// place it is defined.
//
// Returning ALL matches rather than the first is deliberate. A repository
// legitimately defines the same object more than once — a base plus an overlay,
// a per-environment copy, a chart's rendered output committed alongside its
// source. Picking one silently would mean editing the wrong file about as often
// as the right one, and the whole point of Phase 2 is a change that survives
// reconciliation. A caller that gets several must either narrow the search (by
// passing the controller's own reported path) or refuse and ask a human —
// exactly the "refuse rather than guess" rule WORKLOG §121 already applied to
// ambiguous Argo Applications.
func Locate(root string, ref ObjectRef) (LocateResult, error) {
	return LocateIn(root, "", ref)
}

// LocateIn is Locate scoped to a subdirectory of the repository.
//
// Pass the path the GitOps controller itself reports — Argo's
// `spec.source.path`, Flux's Kustomization `spec.path`, a Fleet GitRepo's
// `spec.paths` entry, all of which get_gitops_ownership already resolves
// (WORKLOG §121). This is what turns an ambiguous answer into an actionable
// one, and the need for it was found by running the real thing rather than
// predicted: cloning `argoproj/argocd-example-apps` at the commit ARGUS
// resolved and searching the whole tree found the same `guestbook-ui`
// Deployment TWICE — once in `guestbook/` and once in `kustomize-guestbook/`.
// Both are legitimate; only the one the Application actually points at is the
// file to edit. Searching the whole repo and then guessing would have been
// wrong roughly half the time.
//
// An empty subdir searches the whole tree, which stays the right behaviour when
// the controller reports no path (a repo-root Application) or when no
// controller is known at all.
func LocateIn(root, subdir string, ref ObjectRef) (LocateResult, error) {
	var out LocateResult

	rootAbs, err := filepath.Abs(root)
	if err != nil {
		return out, fmt.Errorf("resolve root: %w", err)
	}
	// Scope the walk, and confine it: a subdir that escapes the repository
	// (via "..", or an absolute path) is refused rather than clamped, because
	// the value originates in a cluster object and silently correcting a
	// traversal attempt would hide it.
	searchRoot := rootAbs
	if clean := strings.Trim(strings.TrimSpace(filepath.ToSlash(subdir)), "/"); clean != "" && clean != "." {
		candidate := filepath.Join(rootAbs, filepath.FromSlash(clean))
		if !isWithin(rootAbs, candidate) {
			return out, fmt.Errorf("gitops: subdir %q escapes the repository root", subdir)
		}
		// A path the controller reports may not exist in the tree at the
		// revision cloned. That is a real, reportable condition — not a reason
		// to silently widen the search back to the whole repo, which would
		// reintroduce exactly the ambiguity this parameter exists to remove.
		info, statErr := os.Stat(candidate)
		if statErr != nil || !info.IsDir() {
			return out, fmt.Errorf("gitops: subdir %q does not exist in this revision", subdir)
		}
		searchRoot = candidate
	}

	walkErr := filepath.WalkDir(searchRoot, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			// An unreadable subtree is skipped, not fatal: a partial answer
			// from a repo with one odd directory is more useful than no
			// answer, and a caller cannot act on "the walk failed" anyway.
			if d != nil && d.IsDir() {
				return fs.SkipDir
			}
			return nil
		}
		if d.IsDir() {
			// .git holds packed objects, not manifests, and is large. Skipping
			// it is a meaningful fraction of the walk cost on any real repo.
			if d.Name() == ".git" {
				return fs.SkipDir
			}
			return nil
		}
		if out.FilesScanned >= maxScannedFiles {
			out.Truncated = true
			return filepath.SkipAll
		}
		if !isYAMLFile(path) {
			return nil
		}
		// Symlinks are not followed. fs.DirEntry reports the link itself, so a
		// symlink is simply not a regular file and is skipped here — which
		// also means a link pointing outside the repo can never be read, the
		// containment property that matters once these repos are
		// attacker-influenced.
		if !d.Type().IsRegular() {
			return nil
		}

		// Relative to the REPOSITORY root, not the search root — a path
		// scoped to a subdir must still be usable for editing and citation.
		rel, relErr := filepath.Rel(rootAbs, path)
		if relErr != nil {
			return nil
		}
		docs, readErr := readDocuments(path)
		if readErr != nil {
			return nil
		}
		out.FilesScanned++
		for i, doc := range docs {
			if documentMatches(doc.node, ref) {
				out.Locations = append(out.Locations, SourceLocation{
					Path:     filepath.ToSlash(rel),
					DocIndex: i,
					Line:     doc.line,
				})
			}
		}
		return nil
	})
	if walkErr != nil {
		return out, fmt.Errorf("walk %s: %w", searchRoot, walkErr)
	}
	return out, nil
}

type document struct {
	node *yaml.Node
	line int
}

// readDocuments parses every YAML document in one file, size-bounded.
func readDocuments(path string) ([]document, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close() //nolint:errcheck

	// Stat rather than reading and then checking: refusing to allocate for an
	// oversized file is the point.
	info, err := f.Stat()
	if err != nil {
		return nil, err
	}
	if info.Size() > maxManifestBytes {
		return nil, fmt.Errorf("%s is %d bytes, over the %d-byte manifest bound", path, info.Size(), maxManifestBytes)
	}

	dec := yaml.NewDecoder(f)
	var docs []document
	for {
		var node yaml.Node
		if err := dec.Decode(&node); err != nil {
			if err == io.EOF {
				break
			}
			// A file that is not valid YAML is not a manifest. Return what
			// parsed so far rather than discarding it: a repo with one broken
			// file should not make every object in its other files
			// unlocatable.
			return docs, nil
		}
		// A document node wraps its single content node.
		content := &node
		line := node.Line
		if node.Kind == yaml.DocumentNode && len(node.Content) == 1 {
			content = node.Content[0]
			line = content.Line
		}
		docs = append(docs, document{node: content, line: line})
	}
	return docs, nil
}

// documentMatches reports whether one parsed YAML document defines ref.
//
// Namespace matching is deliberately lenient in one direction: a manifest that
// declares no namespace is a match for a live object in any namespace, because
// the namespace is very commonly supplied at apply time instead — by the Argo
// CD Application's destination, a Flux Kustomization's targetNamespace, a
// Kustomize namespace transformer, or `kubectl -n`. Requiring it to match
// would fail to find the source file for a large fraction of real GitOps
// repos. A manifest that DOES declare a namespace must match exactly, since
// there the repo is explicit about it.
func documentMatches(node *yaml.Node, ref ObjectRef) bool {
	if node == nil || node.Kind != yaml.MappingNode {
		return false
	}
	kind := scalarAt(node, "kind")
	if !strings.EqualFold(kind, ref.Kind) {
		return false
	}
	// apiVersion is compared on the group only, ignoring the version: a repo
	// pinned at apps/v1beta2 still defines the same object the cluster now
	// serves as apps/v1, and refusing to match across a version bump would
	// mean the source file becomes unfindable exactly when someone needs to
	// update it.
	if ref.APIVersion != "" {
		if !sameAPIGroup(scalarAt(node, "apiVersion"), ref.APIVersion) {
			return false
		}
	}
	meta := mappingValue(node, "metadata")
	if meta == nil {
		return false
	}
	if scalarAt(meta, "name") != ref.Name {
		return false
	}
	if ns := scalarAt(meta, "namespace"); ns != "" && ref.Namespace != "" && ns != ref.Namespace {
		return false
	}
	return true
}

func sameAPIGroup(a, b string) bool {
	return apiGroupOf(a) == apiGroupOf(b)
}

// apiGroupOf returns the group from an apiVersion. "v1" (core) has no group and
// yields "", which is correct and distinct from "apps".
func apiGroupOf(apiVersion string) string {
	if i := strings.Index(apiVersion, "/"); i >= 0 {
		return apiVersion[:i]
	}
	return ""
}

func scalarAt(mapping *yaml.Node, key string) string {
	v := mappingValue(mapping, key)
	if v == nil || v.Kind != yaml.ScalarNode {
		return ""
	}
	return v.Value
}

func mappingValue(mapping *yaml.Node, key string) *yaml.Node {
	if mapping == nil || mapping.Kind != yaml.MappingNode {
		return nil
	}
	// Mapping content alternates key, value.
	for i := 0; i+1 < len(mapping.Content); i += 2 {
		if mapping.Content[i].Value == key {
			return mapping.Content[i+1]
		}
	}
	return nil
}

// isWithin reports whether candidate is inside root after symlink-free
// lexical cleaning. Used to refuse a controller-reported path that escapes the
// repository.
func isWithin(root, candidate string) bool {
	rel, err := filepath.Rel(root, candidate)
	if err != nil {
		return false
	}
	return rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator))
}

func isYAMLFile(path string) bool {
	ext := strings.ToLower(filepath.Ext(path))
	return ext == ".yaml" || ext == ".yml"
}
